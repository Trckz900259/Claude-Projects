def _load_evidence(raw) -> dict:
    if isinstance(raw, dict):
        return raw
    try:
        return json.loads(raw) if raw else {}
    except Exception:
        return {}


def _rel_to(base: Path, target: str) -> str:
    """A relative path from the report dir to a file (for Markdown viewing)."""
    try:
        import os
        return os.path.relpath(target, base)
    except Exception:
        return target


def _repro_steps(f: Any, evidence: dict) -> list[str]:
    subtype = f["subtype"] or "reflected"
    url, param, payload = f["url"], f["parameter"], f["payload"]
    test_url = evidence.get("test_url") or evidence.get("poc_url") or ""
    if subtype == "dom":
        return [
            f"Navigate to `{url}` with the payload in the URL fragment (after `#`).",
            f"Example: `{test_url or url + '#<payload>'}`",
            "The client-side script writes the fragment into a dangerous sink and the "
            "benign `alert()` fires (see PoC).",
        ]
    if subtype == "blind":
        return [
            f"Submit the out-of-band payload into the `{param}` input at `{url}`.",
            "Wait for the stored content to be rendered in a (possibly privileged) view.",
            "Observe the callback recorded by the interactsh listener (correlation id in evidence).",
        ]
    if subtype == "csp":
        return [
            f"Fetch `{url}` and inspect the `Content-Security-Policy` response header.",
            "Compare it against the weaknesses listed above.",
        ]
    return [
        f"Open `{(url or '').split('?')[0]}` in a browser.",
        f"Set the `{param}` parameter to the payload below.",
        f"Full request URL: `{test_url or url}`",
        "Observe the benign `alert()` fire, confirming script execution (see PoC).",
    ]


def _inline_images(html: str, base_dir: Path) -> str:
    """Replace <img src="local"> with base64 data URIs so PDFs are self-contained."""
    def repl(match: re.Match) -> str:
        src = match.group(1)
        if src.startswith("data:") or src.startswith("http"):
            return match.group(0)
        path = (base_dir / src).resolve()
        if not path.exists():
            path = Path(src)
        if not path.exists():
            return match.group(0)
        try:
            data = base64.b64encode(path.read_bytes()).decode("ascii")
            return f'<img src="data:image/png;base64,{data}"'
        except Exception:
            return match.group(0)

    return re.sub(r'<img src="([^"]+)"', repl, html)
