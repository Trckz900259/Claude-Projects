"""
generator.py — consultancy-grade report generation (Markdown + PDF).

For each finding we emit a structured Markdown report containing everything a
program needs to triage and fix it: full HTTP request/response, numbered repro
steps, exact payload + context, the visual PoC, root-cause, CVSS v3.1 +
business impact, context-specific remediation, and CWE/OWASP references. We also
emit ONE consolidated report covering every finding.

PDFs are produced by rendering the report's HTML in the same headless Chromium
we already use for verification (no heavy native PDF dependencies). If Playwright
isn't available, Markdown is still produced and PDF is skipped with a note.

Each per-finding report also carries a clearly-marked "Learning notes" section
(generated by the explain engine for YOU) — delete it before submitting.
"""

